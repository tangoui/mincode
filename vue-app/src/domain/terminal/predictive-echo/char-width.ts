/** 组合字符、零宽字符、变体选择符等：宽度 0，不预测 */
const ZERO_WIDTH_RANGES: ReadonlyArray<readonly [number, number]> = [
  [0x0300, 0x036f], [0x0483, 0x0489], [0x0591, 0x05bd], [0x0610, 0x061a],
  [0x064b, 0x065f], [0x0e31, 0x0e31], [0x0e34, 0x0e3a], [0x0e47, 0x0e4e],
  [0x1160, 0x11ff],   // 谚文中声/终声字母
  [0x1ab0, 0x1aff], [0x1dc0, 0x1dff],
  [0x200b, 0x200f], [0x2028, 0x202e], [0x2060, 0x206f],
  [0x20d0, 0x20ff], [0x302a, 0x302f], [0x3099, 0x309a],
  [0xfe00, 0xfe0f], [0xfe20, 0xfe2f], [0xfeff, 0xfeff],
  [0x1f3fb, 0x1f3ff], // emoji 肤色修饰
  [0xe0000, 0xe0fff],
];

const inRanges = (code: number, ranges: ReadonlyArray<readonly [number, number]>): boolean => {
  let lo = 0;
  let hi = ranges.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [start, end] = ranges[mid];
    if (code < start) hi = mid - 1;
    else if (code > end) lo = mid + 1;
    else return true;
  }
  return false;
};

export function charWidth(char: string): 1 | 2 {
  const code = char.codePointAt(0) ?? 0;
  return inRanges(code, WIDE_RANGES) ? 2 : 1;
}

/** 恰好一个码点、可见且非零宽 */
export function isPredictableChar(char: string): boolean {
  const code = char.codePointAt(0);
  if (code === undefined || char.length !== (code > 0xffff ? 2 : 1)) return false;
  if (code < 0x20 || (code >= 0x7f && code < 0xa0) || code === 0xad) return false;
  if (code >= 0xd800 && code <= 0xdfff) return false;
  return !inRanges(code, ZERO_WIDTH_RANGES);
}
