export function quoteDatabaseIdentifier(connection: DatabaseConnection, identifier: string) {
  if (connection.dbType === "sqlserver") return "[" + identifier.replace(/]/g, "]]") + "]";
  if (mysqlLikeTypes.has(connection.dbType)) return `\`${identifier.replace(/`/g, "``")}\``;
  return `"${identifier.replace(/"/g, '""')}"`;
}

export function qualifiedTableName(
  connection: DatabaseConnection,
  database: string,
  table: string
) {
  const quotedTable = quoteDatabaseIdentifier(connection, table);
  if (connection.dbType === "sqlite" || connection.dbType === "firebird") return quotedTable;
  return `${quoteDatabaseIdentifier(connection, database)}.${quotedTable}`;
}

export function nextTableName(existingTableNames: readonly string[]) {
  const names = new Set(existingTableNames.map((name) => name.toLowerCase()));
  if (!names.has("new_table")) return "new_table";
  let suffix = 2;
  while (names.has(`new_table_${suffix}`)) suffix += 1;
  return `new_table_${suffix}`;
}

export function createTableTemplate(
  connection: DatabaseConnection,
  database: string,
  existingTableNames: readonly string[]
) {
  const tableName = qualifiedTableName(
    connection,
    database,
    nextTableName(existingTableNames)
  );
  if (connection.dbType === "pgvector") {
    return `CREATE TABLE ${tableName} (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  embedding vector(1536) NOT NULL,
  metadata JSONB
);`;
  }
  if (mysqlLikeTypes.has(connection.dbType)) {
    return `CREATE TABLE ${tableName} (\n  \`id\` BIGINT NOT NULL AUTO_INCREMENT,\n  \`created_at\` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,\n  PRIMARY KEY (\`id\`)\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;`;
  }
  if (postgresLikeTypes.has(connection.dbType)) {
    return `CREATE TABLE ${tableName} (\n  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n  "created_at" TIMESTAMPTZ NOT NULL DEFAULT NOW()\n);`;
  }
  if (connection.dbType === "sqlite") {
    return `CREATE TABLE ${tableName} (\n  "id" INTEGER PRIMARY KEY AUTOINCREMENT,\n  "created_at" TEXT NOT NULL DEFAULT (datetime('now'))\n);`;
  }
  if (connection.dbType === "sqlserver") {
    return `CREATE TABLE ${tableName} (\n  [id] BIGINT IDENTITY(1,1) PRIMARY KEY,\n  [created_at] DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()\n);`;
  }
  if (connection.dbType === "firebird") {
    return `CREATE TABLE ${tableName} (\n  "id" BIGINT NOT NULL PRIMARY KEY,\n  "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP\n);`;
  }
  return `CREATE TABLE ${tableName} (\n  id BIGINT PRIMARY KEY,\n  created_at TIMESTAMP\n);`;
}

export function schemaExportFilename(database: string) {
  return `${database.replace(/[\\/:*?"<>|]/g, "_") || "database"}_schema.sql`;
}

export function sqlFileTabName(path: string, fallbackName: string) {
  const fileName = path.split(/[\\/]/).pop() || fallbackName;
  return fileName.replace(/\.sql$/i, "") || fileName;
}

export type TableDataFormat = "csv" | "json" | "xlsx" | "markdown" | "sql" | "txt";

const tableDataFormatExtensions: Record<TableDataFormat, string> = {
  csv: "csv",
  json: "json",
  xlsx: "xlsx",
  markdown: "md",
  sql: "sql",
  txt: "txt",
};

export function tableDataFormatExtension(format: TableDataFormat) {
  return tableDataFormatExtensions[format];
}

/** 二进制格式（xlsx）后端以 base64 返回，需走二进制写盘。 */
export function tableDataFormatIsBinary(format: TableDataFormat) {
  return format === "xlsx";
}

export function tableDataFilename(database: string, table: string, format: TableDataFormat) {
  const safe = (value: string) => value.replace(/[\\/:*?"<>|]/g, "_") || "table";
  return `${safe(database)}_${safe(table)}.${tableDataFormatExtension(format)}`;
}

export function tableDataFormatFromPath(path: string): TableDataFormat | undefined {
  const name = path.split(/[\\/]/).pop()?.toLowerCase() ?? "";
  if (name.endsWith(".csv")) return "csv";
  if (name.endsWith(".json")) return "json";
  return undefined;
}
