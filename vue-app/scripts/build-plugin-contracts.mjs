// Copies the plugin contribution-point contract
// (plugins/api/contribution-points.json, the single source of truth)
// to every consumer that cannot import the Go package, copies shared
// single-file Go packages into the plugin CLI (a separate module),
// regenerates the devkit manifest schema and copies it into the plugin CLI.
// `--check` fails on drift without writing.
//
//   pnpm --dir vue-app build:plugin-contracts
//   pnpm --dir vue-app check:plugin-contracts
import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateManifestSchema, renderManifestSchema } from '../../tools/plugin-devkit/generate-schema.mjs';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const contractSource = resolve(repo, 'plugins/api/contribution-points.json');

// Every copy is byte-identical to the source. Add a consumer here, never a
// second hand-maintained contract. The plugin CLI embeds its copy with
// go:embed, so it must be committed next to its Go sources.
export const contractCopies = [
  'tools/mincode-cli/contribution-points.json',
  'tools/plugin-devkit/contribution-points.json',
  'cloud/app/common/service/Mincode/contribution-points.json',
  'vue-app/src/domain/plugins/contribution-points.json',
];

// Shared dependency-free Go sources the plugin CLI (module mincode-cli,
// package main) compiles verbatim: the package clause is rewritten to `main`
// and a generated-file header is prepended. tools/mincode-cli/build globs
// *.go, so the copy ships with the CLI automatically.
export const generatedGoSources = [
  { source: 'plugins/api/externalopen/catalog.go', target: 'tools/mincode-cli/external_open_catalog_gen.go', packageName: 'main' },
  { source: 'plugins/api/svgsafe/svgsafe.go', target: 'tools/mincode-cli/svgsafe_gen.go', packageName: 'main' },
  { source: 'plugins/api/codetmpl/codetmpl.go', target: 'tools/mincode-cli/codetmpl_gen.go', packageName: 'main' },
];

// Copy of the devkit manifest schema that the plugin CLI embeds for `mincode
// plugin schema`. Like the generated Go sources it is written with LF and
// checked ignoring CRLF, so it stays identical to the devkit schema in any
// checkout.
export const manifestSchemaCopy = 'tools/mincode-cli/manifest.schema.json';

export function renderGeneratedGoSource(sourcePath, text, packageName) {
  text = text.replace(/\r\n/g, '\n');
  const clause = /^package [A-Za-z_][A-Za-z0-9_]*$/m;
  if (!clause.test(text)) throw new Error(`${sourcePath}: package clause not found`);
  const header = `// Code generated by vue-app/scripts/build-plugin-contracts.mjs from ${sourcePath}; DO NOT EDIT.\n\n`;
  return header + text.replace(clause, `package ${packageName}`);
}

const optionalRoots = ['cloud/'];

// 使用单字节映射仅转换 CRLF，避免 UTF-8 解码掩盖其他字节漂移。
function sameIgnoringCRLF(current, next) {
  return current !== null && Buffer.from(current.toString('latin1').replace(/\r\n/g, '\n'), 'latin1').equals(next);
}

async function readOptional(path) {
  return readFile(path).catch(error => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
}

async function exists(path) {
  return access(path).then(() => true, () => false);
}

export async function buildPluginContracts({ check = false } = {}) {
  const source = await readFile(contractSource);
  JSON.parse(source.toString('utf8'));
  const stale = [];
  const written = [];
  for (const copy of contractCopies) {
    const target = resolve(repo, copy);
    // cloud/ is a separate repository; skip it when it is not checked out.
    if (optionalRoots.some(root => copy.startsWith(root)) && !(await exists(dirname(target)))) continue;
    const current = await readOptional(target);
    if (current !== null && current.equals(source)) continue;
    if (check) {
      stale.push(copy);
      continue;
    }
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, source);
    written.push(copy);
  }
  for (const { source: goSource, target: goTarget, packageName } of generatedGoSources) {
    const next = Buffer.from(renderGeneratedGoSource(goSource, await readFile(resolve(repo, goSource), 'utf8'), packageName));
    const target = resolve(repo, goTarget);
    if (sameIgnoringCRLF(await readOptional(target), next)) continue;
    if (check) {
      stale.push(goTarget);
      continue;
    }
    await writeFile(target, next);
    written.push(goTarget);
  }
  const schema = await generateManifestSchema({ check });
  if (schema.stale) stale.push(relative(repo, schema.path));
  else if (schema.written) written.push(relative(repo, schema.path));
  const schemaText = Buffer.from(await renderManifestSchema());
  const schemaTarget = resolve(repo, manifestSchemaCopy);
  if (!sameIgnoringCRLF(await readOptional(schemaTarget), schemaText)) {
    if (check) stale.push(manifestSchemaCopy);
    else {
      await writeFile(schemaTarget, schemaText);
      written.push(manifestSchemaCopy);
    }
  }
  if (stale.length) {
    throw new Error(`Stale plugin contract copies: ${stale.join(', ')}. Run pnpm --dir vue-app build:plugin-contracts`);
  }
  return written;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const written = await buildPluginContracts({ check });
  console.log(check ? 'Plugin contracts are up to date.' : written.length ? `Updated: ${written.join(', ')}` : 'Plugin contracts already up to date.');
}
