package backend

import (
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// backendCommandsCatalog is the generated TypeScript list of registered commands.
// Regenerate with: UPDATE_BACKEND_COMMANDS=1 go test ./backend -run TestBackendCommandsCatalog
var backendCommandsCatalog = filepath.Join("..", "vue-app", "src", "generated", "backend-commands.ts")

func renderBackendCommandsCatalog(commands []string) string {
	sorted := append([]string(nil), commands...)
	sort.Strings(sorted)
	var b strings.Builder
	b.WriteString("// This file is generated by backend/commands_catalog_test.go. DO NOT EDIT.\n")
	b.WriteString("// Regenerate: UPDATE_BACKEND_COMMANDS=1 go test ./backend -run TestBackendCommandsCatalog\n\n")
	b.WriteString("export const BACKEND_COMMANDS = [\n")
	for _, command := range sorted {
		b.WriteString("  \"")
		b.WriteString(command)
		b.WriteString("\",\n")
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type BackendCommand = (typeof BACKEND_COMMANDS)[number];\n")
	return b.String()
}

func normalizeCatalogLineEndings(text string) string {
	return strings.ReplaceAll(text, "\r\n", "\n")
}

func TestCatalogLineEndingNormalization(t *testing.T) {
	want := renderBackendCommandsCatalog([]string{"alpha", "beta"})
	for _, got := range []string{want, strings.ReplaceAll(want, "\n", "\r\n")} {
		if normalizeCatalogLineEndings(got) != want {
			t.Fatal("LF and CRLF catalogs must compare equally")
		}
	}
	for _, got := range []string{
		strings.Replace(want, "alpha", "changed", 1),
		strings.Replace(want, "  \"alpha\"", " \"alpha\"", 1),
		want + "\n",
		strings.Replace(want, "\n", "\r", 1),
	} {
		if normalizeCatalogLineEndings(got) == want {
			t.Fatal("content, whitespace, trailing lines and bare CR must remain significant")
		}
	}
}

func TestBackendCommandsCatalog(t *testing.T) {
	want := renderBackendCommandsCatalog(Commands())
	if os.Getenv("UPDATE_BACKEND_COMMANDS") == "1" {
		if err := os.MkdirAll(filepath.Dir(backendCommandsCatalog), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(backendCommandsCatalog, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(backendCommandsCatalog)
	if err != nil {
		t.Fatalf("read %s: %v (regenerate with UPDATE_BACKEND_COMMANDS=1)", backendCommandsCatalog, err)
	}
	// Git may check out the generated text with CRLF on Windows. Only line
	// endings are insignificant; command names, ordering and other bytes must match.
	if normalizeCatalogLineEndings(string(got)) != want {
		t.Fatalf("%s is stale; regenerate with UPDATE_BACKEND_COMMANDS=1 go test ./backend -run TestBackendCommandsCatalog", backendCommandsCatalog)
	}
}
