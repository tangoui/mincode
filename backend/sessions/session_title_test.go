// claudeTranscript 拼出一段接近真实 JSONL 的转录：首尾各一条真人输入，
// 中间夹着工具结果和 Claude 自己注入的包装条目。
func claudeTranscript(lines ...string) string {
	return strings.Join(lines, "\n") + "\n"
}

const (
	caveatLine = `{"type":"user","message":{"role":"user","content":"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"},"isMeta":true,"uuid":"a"}`
	firstAsk   = `{"type":"user","message":{"role":"user","content":"帮我看下 geo 模块的第三方授权"},"userType":"external","uuid":"b"}`
	toolResult = `{"type":"user","message":{"role":"user","content":[{"tool_use_id":"toolu_1","type":"tool_result","content":"微信相关动作数: 0","is_error":false}]},"toolUseResult":{"stdout":"微信相关动作数: 0"},"uuid":"c"}`
	sidechain  = `{"type":"user","isSidechain":true,"message":{"role":"user","content":"子代理的提示词"},"uuid":"d"}`
	lastAsk    = `{"type":"user","message":{"role":"user","content":[{"type":"text","text":"再帮我清理下系统垃圾"}]},"userType":"external","uuid":"e"}`
)

func writeTranscript(t *testing.T, content string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "session.jsonl")
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestReadJsonlPrefixAndCountReportsTheLastHumanPrompt(t *testing.T) {
	path := writeTranscript(t, claudeTranscript(caveatLine, firstAsk, toolResult, sidechain, lastAsk, toolResult))

	prefix, lastPrompt, count := readJsonlPrefixAndCount(path, 96*1024, unknownFileSize)
	if lastPrompt != "再帮我清理下系统垃圾" {
		t.Fatalf("lastPrompt = %q, want the final human prompt", lastPrompt)
	}
	if count != 6 {
		t.Fatalf("count = %d, want 6", count)
	}
	if !strings.Contains(prefix, "geo") {
		t.Fatalf("prefix lost the opening prompt: %q", prefix)
	}
}

func TestReadJsonlPrefixAndCountWithSizeHint(t *testing.T) {
	const limit = 96 * 1024
	const firstPrompt = "帮我看下 geo 模块的第三方授权"
	const finalPrompt = "再帮我清理下系统垃圾"
	const assistantStart = `{"type":"assistant","message":{"content":"`
	const assistantEnd = `界"}}` + "\n"
	opening := firstAsk + "\n"
	transcriptOfSize := func(size int) string {
		padding := size - len(opening) - len(assistantStart) - len(assistantEnd)
		return opening + assistantStart + strings.Repeat("x", padding) + assistantEnd
	}
	below, exact := transcriptOfSize(limit-1), transcriptOfSize(limit)
	// Place the prefix boundary inside the final rune of this assistant line.
	beyond := transcriptOfSize(limit - 1 + len(assistantEnd))
	shortGrowth := opening + "\n" + lastAsk
	for _, tc := range []struct {
		name       string
		before     string
		after      string
		wantPrefix string
		wantPrompt string
		wantCount  uint32
	}{
		{name: "empty"},
		{
			name: "below limit", before: below, after: below,
			wantPrefix: below, wantPrompt: firstPrompt, wantCount: 2,
		},
		{
			name: "at limit", before: exact, after: exact,
			wantPrefix: exact, wantPrompt: firstPrompt, wantCount: 2,
		},
		{
			name: "beyond limit", before: beyond + lastAsk, after: beyond + lastAsk,
			wantPrefix: beyond[:limit], wantPrompt: finalPrompt, wantCount: 3,
		},
		{
			name: "grew below limit", before: opening, after: shortGrowth,
			wantPrefix: shortGrowth, wantPrompt: finalPrompt, wantCount: 2,
		},
		{
			name: "grew past limit", after: beyond + lastAsk,
			wantPrefix: beyond[:limit], wantPrompt: finalPrompt, wantCount: 3,
		},
		{
			name: "truncated", before: beyond, after: lastAsk,
			wantPrefix: lastAsk, wantPrompt: finalPrompt, wantCount: 1,
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			path := writeTranscript(t, tc.before)
			info, err := os.Stat(path)
			if err != nil {
				t.Fatal(err)
			}
			if tc.before != tc.after {
				if err := os.WriteFile(path, []byte(tc.after), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			prefix, prompt, count := readJsonlPrefixAndCount(path, limit, info.Size())
			if prefix != tc.wantPrefix {
				t.Errorf("prefix differs from expected bytes (got %d bytes, want %d)", len(prefix), len(tc.wantPrefix))
			}
			if prompt != tc.wantPrompt || count != tc.wantCount {
				t.Errorf("got prompt %q, count %d; want %q, %d", prompt, count, tc.wantPrompt, tc.wantCount)
			}
		})
	}
}

func TestReadJsonlPrefixAndCountWithSizeHintOnOpenOrReadError(t *testing.T) {
	dir := t.TempDir()
	for _, path := range []string{filepath.Join(dir, "missing.jsonl"), dir} {
		if prefix, prompt, count := readJsonlPrefixAndCount(path, 96*1024, 42); prefix != "" || prompt != "" || count != 0 {
			t.Errorf("got prefix %q, prompt %q, count %d for %s; want empty result", prefix, prompt, count, path)
		}
	}
}

func TestLastHumanPromptSkipsToolResultsAndInjectedEntries(t *testing.T) {
	// 只跑过斜杠命令的会话没有任何真人输入，标题必须留空交给上层回退。
	path := writeTranscript(t, claudeTranscript(caveatLine, toolResult, sidechain))
	if _, lastPrompt, _ := readJsonlPrefixAndCount(path, 96*1024, unknownFileSize); lastPrompt != "" {
		t.Fatalf("lastPrompt = %q, want empty for a transcript without human input", lastPrompt)
	}

	for name, line := range map[string]string{
		"tool result":   toolResult,
		"caveat":        caveatLine,
		"sidechain":     sidechain,
		"empty content": `{"type":"user","message":{"role":"user","content":[]},"uuid":"f"}`,
		"assistant":     `{"type":"assistant","message":{"role":"assistant","content":"好的"},"uuid":"g"}`,
		// 后台任务回执和压缩续写都是 Claude 写进转录的，用户没有发过。
		"task notification": `{"type":"user","message":{"role":"user","content":"<task-notification> <task-id>abc</task-id>"},"uuid":"h"}`,
		"compaction":        `{"type":"user","message":{"role":"user","content":"This session is being continued from a previous conversation that ran out of context."},"uuid":"i"}`,
	} {
		if title := claudePromptTitle(line); title != "" {
			t.Fatalf("%s must not become a title, got %q", name, title)
		}
	}
}

func TestHumanPromptTextIgnoresToolResultBlocks(t *testing.T) {
	// extractContentText 会把 tool_result 拼进来，标题不能复用它。
	content := []byte(`[{"type":"tool_result","content":"stdout"},{"type":"text","text":"真正说的话"}]`)
	if got := humanPromptText(content); got != "真正说的话" {
		t.Fatalf("humanPromptText() = %q", got)
	}
}

func TestProjectSessionsPreferTheLastPromptOverTheOpeningOne(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "5fcaa2b5-f87d-4951-b1df-b502e6cf248e.jsonl")
	if err := os.WriteFile(path, []byte(claudeTranscript(caveatLine, firstAsk, toolResult, lastAsk)), 0o600); err != nil {
		t.Fatal(err)
	}

	prefix, lastPrompt, _ := readJsonlPrefixAndCount(path, 96*1024, unknownFileSize)
	openingTitle := ""
	jsonLines(prefix, func(v map[string]json.RawMessage) {
		if openingTitle == "" {
			openingTitle = claudePromptTitleFromEntry(v)
		}
	})
	if openingTitle != "帮我看下 geo 模块的第三方授权" {
		t.Fatalf("opening title = %q, want the first human prompt rather than the caveat", openingTitle)
	}
	if lastPrompt == openingTitle {
		t.Fatalf("last prompt must differ from the opening one: %q", lastPrompt)
	}
}
